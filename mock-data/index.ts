const smsReviewWording =
  'I agree to receive a one-time review request by text from {business}. Reply STOP to opt out. Message and data rates may apply.'
const emailReviewWording =
  'I agree to receive a one-time review request by email from {business}. I can unsubscribe at any time.'
const promoWording =
  'I agree to receive occasional offers and updates by text from {business}. Consent is not a condition of purchase. Reply STOP to opt out.'

function consent(
  id: string,
  customerId: string,
  organizationId: string,
  channel: 'sms' | 'email',
  purpose: 'review_request' | 'promotional',
  status: 'granted' | 'withdrawn',
  capturedDaysAgo: number,
  source = 'Booking form',
): Consent {
  return {
    id,
    organization_id: organizationId,
    customer_id: customerId,
    channel,
    purpose,
    status,
    source,
    wording_text:
      purpose === 'promotional'
        ? promoWording.replace('{business}', organizationId === 'org_roof' ? 'Sample Roofing Co.' : 'Sample HVAC Services')
        : (channel === 'sms' ? smsReviewWording : emailReviewWording).replace(
            '{business}',
            organizationId === 'org_roof' ? 'Sample Roofing Co.' : 'Sample HVAC Services',
          ),
    wording_version: '2026-01-v1',
    captured_at: daysAgo(capturedDaysAgo),
  }
}

